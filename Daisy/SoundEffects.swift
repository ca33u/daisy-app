//
//  SoundEffects.swift
//  Daisy
//
//  Tiny audio cues for recording lifecycle events. Daisy's own «Капля»
//  (two bundled WAVs, scripts/sounds/drop.py) for dictation and for a
//  meeting's start and finish; macOS built-in `NSSound`-named system
//  sounds for the rest (`/System/Library/Sounds/`, the same names since
//  the System 7 era).
//
//  History: `Tink` once signalled "armed" for meeting starts but read as
//  a system-edge ping (volume max, unhandled key), so every hotkey tap
//  felt like a mis-press; `Purr` replaced it, then «Капля» replaced Purr
//  (dictation 31.10, meetings 01.11). Voice notes keep `Pop` so quick
//  taps stay audibly distinct from the longer recording modes.
//
//  Selection (2026-05-31 — pared back after the 4-lens A/V review):
//   • Start (meeting)    → «Капля» (DaisyDropStart.wav) — since 01.11, was "Purr"
//   • Start (voice note) → "Pop"    — soft accent, neutral
//   • Start (dictation)  → «Капля» (DaisyDropStart.wav) — our own, 31.10
//   • Dictation inserted → «Капля» (DaisyDropDone.wav)
//   • Finished           → «Капля» (DaisyDropDone.wav) — since 01.11, was
//                                     "Glass"; fired the instant `.finished`
//                                     lands so it syncs with the widget's
//                                     celebration pop
//   • Failed             → "Sosumi" — distinct, gentle "something's wrong"
//
//  Pause / Resume cues were REMOVED: they fired mid-capture (the worst
//  leak window — on built-in speakers the loopback records them, and on
//  macOS 26 self-exclusion is off), and the widget colour already carries
//  the state (gray ↔ orange). The old Stop-click cue was likewise dropped —
//  it fired BEFORE capture stopped (tailing the recording) and before any
//  work finished; the "done" signal now lives on `.finished`.
//  `playPause` / `playResume` / `playStop` are kept below, unused, for
//  reference / quick revert.
//
//  ⚠️ KNOWN GAPS (dev / design): the Start cue can still be captured on
//  macOS 26 until the SystemAudioCapture self-exclusion split is restored.
//  Pop and Sosumi are still system placeholders; the error cue would want
//  a drop of its own. See the 2026-05-31 review note.
//
//  Volume (system sounds): each NSSound starts at 1.0; we set 0.4 to keep cues
//  noticeable but not jarring. Recording-app sounds that boom
//  through office speakers are a usability hazard.
//
//  All entry points respect `AppSettings.recordingSoundsEnabled`
//  via the call sites in `RecordingSession`; this file just
//  plays — it doesn't gate.
//

import AppKit

@MainActor
enum SoundEffects {
    static func playStart(for mode: RecordingSession.RecordingMode = .meeting) {
        switch mode {
        case .meeting:   playBundled(dropStart)
        case .voiceNote: play(named: "Pop")
        case .dictation: playBundled(dropStart)
        }
    }

    /// Dictation's text landed in the field (pasted, typed or inserted).
    static func playDictationDone() { playBundled(dropDone) }

    // Daisy's own cues (31.10, Egor: «маленький, тонкий, приятный, вообще
    // слегка заметный»): «Капля», generated by scripts/sounds/drop.py — a
    // water drop since 01.11 (the first bell was «писклявый и системный»),
    // and on meetings too. Quiet in the file itself (peak ≈ -17 dBFS), so
    // they play at full volume. Loaded once.
    private static let dropStart = bundledSound("DaisyDropStart")
    private static let dropDone = bundledSound("DaisyDropDone")

    private static func bundledSound(_ name: String) -> NSSound? {
        let url = Bundle.main.url(forResource: name, withExtension: "wav", subdirectory: "Sounds")
            ?? Bundle.main.url(forResource: name, withExtension: "wav")
        return url.flatMap { NSSound(contentsOf: $0, byReference: true) }
    }

    private static func playBundled(_ sound: NSSound?) {
        guard let sound else { return }
        sound.stop()
        sound.volume = 1.0
        sound.play()
    }
    static func playPause()   { play(named: "Pop") }
    static func playResume()  { play(named: "Purr", fallback: "Pop") }
    static func playStop()    { play(named: "Glass") }

    /// Played the instant the session lands in `.finished` (transcript
    /// ready, user unblocked) — lands with the widget's celebration pop.
    /// This is the real "done", replacing the old stop-click cue that
    /// fired before any work finished AND could tail into the recording.
    static func playFinished() { playBundled(dropDone) }

    /// Played when a recording fails / is lost. Distinct from the success
    /// cues so "something went wrong" is unmistakable, but not alarming.
    /// (Provisional system sound — a bespoke error tone is the real fix.)
    static func playError()    { play(named: "Sosumi", fallback: "Funk") }

    private static func play(named name: String, fallback: String? = nil) {
        // `NSSound(named:)` returns nil for unknown names — keep
        // the silent fallback rather than crashing if Apple ever
        // renames a system sound. `Purr` isn't on every macOS 14
        // build, hence its `fallback` ("Pop").
        if let sound = NSSound(named: name) {
            sound.volume = 0.4
            sound.play()
            return
        }
        if let fallback, let sound = NSSound(named: fallback) {
            sound.volume = 0.4
            sound.play()
        }
    }
}
