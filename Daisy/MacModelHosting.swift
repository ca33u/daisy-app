//
//  MacModelHosting.swift
//  Daisy
//
//  Models from our own mirror first (backlog 31 У-1, 2026-10-21).
//
//  Daisy for Mac downloaded every model straight from Hugging Face through
//  WhisperKit and FluidAudio, from whatever `main` was that day, checked
//  against nothing. If HF were down, a repository removed or its rules
//  changed, a new Mac couldn't transcribe. Now each model is fetched by
//  Daisy itself, before the library is asked to load it:
//
//    1. the file list and every file's size and SHA-256 come only from the
//       manifest in the app bundle (`ModelsManifest.json`, generated by
//       `scripts/models-sync.sh prepare` from `Docs/models-sources.json`);
//    2. each file comes from `models.mydaisy.io` (Cloudflare R2, the same
//       pinned copies the iPhone uses); if that fails or the bytes are
//       wrong, from Hugging Face at the pinned commit;
//    3. a file is put in place only after its size and SHA-256 match.
//
//  The files land in the caches the libraries read — WhisperKit's model
//  folder (with the tokenizer inside it, so nothing goes to ~/Documents),
//  FluidAudio's `Models/<repo>` — so they then load offline as before. If
//  this fails altogether, the library's own Hugging Face download is still
//  the last resort: a Mac is never worse off than before.
//
//  Ported from DaisyLite's `ModelHosting` / `VerifiedModelFetch`.
//

import CryptoKit
import FluidAudio
import Foundation
import os

nonisolated enum MacModelHosting {
    static let mirror = "https://models.mydaisy.io"
    static let whisperRepo = "argmaxinc/whisperkit-coreml"
    static let tokenizerRepo = "openai/whisper-large-v3"

    /// A set of files one model needs, with where they go.
    enum ModelSet: Sendable {
        /// A WhisperKit variant («large-v3-v20240930_626MB»), its tokenizer
        /// inside its folder.
        case whisper(variant: String)
        case parakeetV3
        case sileroVAD
        case diarizer
        /// «Локальная модель Daisy» (Qwen 3.5 4B, MLX 4-bit), read by the
        /// DaisyLLM helper. Fetched only when the person chooses it, and with
        /// no library download behind it.
        case summaryLLM

        var name: String {
            switch self {
            case .whisper(let variant): "Whisper \(variant)"
            case .parakeetV3: "Parakeet v3"
            case .sileroVAD: "Silero VAD"
            case .diarizer: "speaker models"
            case .summaryLLM: "local summary model"
            }
        }
    }

    struct File: Decodable, Sendable, Equatable {
        let repo: String
        let revision: String
        let path: String
        let size: Int64
        let runtime: Bool
        let sha256: String
    }

    /// One file to fetch: the manifest entry and its place under the
    /// destination directory.
    struct Entry: Sendable, Equatable {
        let file: File
        let localPath: String
    }

    enum Failure: Error, LocalizedError {
        case invalidCatalog
        case notInCatalog
        case integrity
        var errorDescription: String? {
            switch self {
            case .invalidCatalog: "The bundled model catalog is invalid."
            case .notInCatalog: "This model isn't in the bundled catalog."
            case .integrity: String(localized: "The model could not be downloaded intact. Check the connection and try again.")
            }
        }
    }

    private static let log = Logger(subsystem: "app.essazanov.Daisy", category: "ModelHosting")

    // MARK: Catalog

    private struct Catalog: Decodable {
        let schemaVersion: Int
        let files: [File]
    }

    static func safePath(_ path: String) -> Bool {
        !path.isEmpty && path.split(separator: "/", omittingEmptySubsequences: false).allSatisfy {
            !$0.isEmpty && $0 != "." && $0 != ".." && $0.allSatisfy {
                $0.isASCII && ($0.isLetter || $0.isNumber || "._-".contains($0))
            }
        }
    }

    private static func hex(_ value: String, count: Int) -> Bool {
        value.count == count && value.allSatisfy { "0123456789abcdef".contains($0) }
    }

    /// The runtime files, validated. Expectations come only from the app
    /// bundle — never from either download host.
    static func decodeCatalog(_ data: Data) throws -> [File] {
        let catalog = try JSONDecoder().decode(Catalog.self, from: data)
        guard catalog.schemaVersion == 1, !catalog.files.isEmpty else { throw Failure.invalidCatalog }
        var identities = Set<String>()
        for file in catalog.files {
            guard safePath(file.repo), file.repo.split(separator: "/").count == 2,
                  safePath(file.path), file.size > 0,
                  hex(file.revision, count: 40), hex(file.sha256, count: 64),
                  identities.insert(file.repo + "/" + file.path).inserted else { throw Failure.invalidCatalog }
        }
        return catalog.files.filter(\.runtime)
    }

    static func catalog(bundle: Bundle = .main) throws -> [File] {
        guard let url = bundle.url(forResource: "ModelsManifest", withExtension: "json") else {
            throw Failure.invalidCatalog
        }
        return try decodeCatalog(Data(contentsOf: url))
    }

    /// What a model set needs, and where each file goes under its
    /// destination (`destination(for:)`).
    static func entries(for set: ModelSet, in files: [File]) throws -> [Entry] {
        func bundle(_ repo: String, _ roots: [String]) throws -> [Entry] {
            let selected = files.filter { file in
                file.repo == repo && roots.contains { file.path == $0 || file.path.hasPrefix($0 + "/") }
            }
            // Every root has to be there, or the library would find a half
            // model and go to Hugging Face for the rest.
            guard roots.allSatisfy({ root in
                selected.contains { $0.path == root || $0.path.hasPrefix(root + "/") }
            }) else { throw Failure.notInCatalog }
            return selected.map { Entry(file: $0, localPath: $0.path) }
        }
        switch set {
        case .whisper(let variant):
            let folder = "openai_whisper-\(variant)"
            let model = files.filter { $0.repo == whisperRepo && $0.path.hasPrefix(folder + "/") }
            // tokenizer.json and its config; the tokenizer repo's own
            // config.json would land on the variant's config.json (review
            // 21.10) — the tokenizer loader takes the variant's.
            let tokenizer = files.filter { $0.repo == tokenizerRepo && $0.path != "config.json" }
            guard model.contains(where: { $0.path.hasPrefix(folder + "/AudioEncoder.mlmodelc/") }),
                  tokenizer.contains(where: { $0.path == "tokenizer.json" }) else { throw Failure.notInCatalog }
            // The tokenizer goes INSIDE the variant folder: WhisperKit looks
            // there second, and offline — instead of fetching it from
            // Hugging Face into ~/Documents.
            return model.map { Entry(file: $0, localPath: $0.path) }
                + tokenizer.map { Entry(file: $0, localPath: folder + "/" + $0.path) }
        case .parakeetV3:
            return try bundle("FluidInference/parakeet-tdt-0.6b-v3-coreml",
                              ["Preprocessor.mlmodelc", "Encoder.mlmodelc", "Decoder.mlmodelc",
                               "JointDecisionv3.mlmodelc", "parakeet_vocab.json"])
        case .sileroVAD:
            return try bundle("FluidInference/silero-vad-coreml", ["silero-vad-unified-256ms-v6.2.1.mlmodelc"])
        case .diarizer:
            return try bundle("FluidInference/speaker-diarization-coreml",
                              ["pyannote_segmentation.mlmodelc", "wespeaker_v2.mlmodelc"])
        case .summaryLLM:
            return try bundle(LocalSummaryModel.repo, LocalSummaryModel.files)
        }
    }

    /// The directory the library reads the set from.
    static func destination(for set: ModelSet, whisperRoot: URL? = nil) -> URL? {
        switch set {
        case .whisper: whisperRoot
        case .parakeetV3: AsrModels.defaultCacheDirectory(for: .v3)
        case .sileroVAD: MLModelConfigurationUtils.defaultModelsDirectory(for: .vad)
        case .diarizer: DiarizerModels.defaultModelsDirectory()
        case .summaryLLM: LocalSummaryModel.directory
        }
    }

    // MARK: Fetching

    enum Source: String, Sendable { case mirror, huggingFace }

    static func url(for file: File, source: Source) throws -> URL {
        guard safePath(file.repo), safePath(file.path), hex(file.revision, count: 40) else {
            throw Failure.invalidCatalog
        }
        // The mirror serves the pinned copy as `main`; Hugging Face is
        // asked for the pinned commit, never its moving `main`.
        let base = source == .mirror ? mirror : "https://huggingface.co"
        let ref = source == .mirror ? "main" : file.revision
        guard let url = URL(string: "\(base)/\(file.repo)/resolve/\(ref)/\(file.path)") else {
            throw Failure.invalidCatalog
        }
        return url
    }

    static func sha256(of url: URL) -> String? {
        do {
            let handle = try FileHandle(forReadingFrom: url)
            defer { try? handle.close() }
            var hash = SHA256()
            while let chunk = try handle.read(upToCount: 4 << 20), !chunk.isEmpty { hash.update(data: chunk) }
            return hash.finalize().map { String(format: "%02x", $0) }.joined()
        } catch { return nil } // A read error must never produce a hash of a readable prefix.
    }

    static func valid(_ file: File, at url: URL) -> Bool {
        guard let size = try? url.resourceValues(forKeys: [.fileSizeKey]).fileSize,
              Int64(size) == file.size else { return false }
        return sha256(of: url) == file.sha256
    }

    typealias Fetch = @Sendable (URL, @escaping @Sendable (Int64) -> Void) async throws -> (URL, URLResponse)

    /// Fetches a model set into `directory`: files already there and intact
    /// are kept, the rest come from the mirror, then from Hugging Face at
    /// the pinned commit, each verified before it's put in place.
    /// `progress` gets the share of the set's bytes in place (0…1).
    static func prefetch(_ set: ModelSet, into directory: URL,
                         progress: (@Sendable (Double) -> Void)? = nil,
                         fetch: Fetch? = nil, catalog files: [File]? = nil) async throws {
        let entries = try entries(for: set, in: files ?? catalog())
        let total = max(1, entries.reduce(0) { $0 + $1.file.size })
        let done = ByteCounter()
        let fetcher = fetch ?? defaultFetch
        for entry in entries {
            try Task.checkCancellation()
            let target = directory.appendingPathComponent(entry.localPath)
            if valid(entry.file, at: target) {
                progress?(Double(done.add(entry.file.size)) / Double(total))
                continue
            }
            try await ensure(entry, at: target, fetch: fetcher) { written in
                progress?(Double(done.peek() + written) / Double(total))
            }
            progress?(Double(done.add(entry.file.size)) / Double(total))
        }
        log.info("\(set.name, privacy: .public): \(entries.count, privacy: .public) files verified")
    }

    private static func ensure(_ entry: Entry, at target: URL, fetch: Fetch,
                               written: @escaping @Sendable (Int64) -> Void) async throws {
        var lastError: Error = Failure.integrity
        for source in [Source.mirror, .huggingFace] {
            try Task.checkCancellation()
            do {
                let (temporary, response) = try await fetch(url(for: entry.file, source: source), written)
                defer { try? FileManager.default.removeItem(at: temporary) }
                try Task.checkCancellation()
                guard let status = (response as? HTTPURLResponse)?.statusCode, (200..<300).contains(status),
                      valid(entry.file, at: temporary) else { throw Failure.integrity }
                try FileManager.default.createDirectory(at: target.deletingLastPathComponent(), withIntermediateDirectories: true)
                // A sibling, so the replace stays on the destination volume.
                let incoming = target.deletingLastPathComponent().appendingPathComponent(".incoming-" + UUID().uuidString)
                defer { try? FileManager.default.removeItem(at: incoming) }
                try FileManager.default.moveItem(at: temporary, to: incoming)
                if FileManager.default.fileExists(atPath: target.path) {
                    _ = try FileManager.default.replaceItemAt(target, withItemAt: incoming)
                } else {
                    try FileManager.default.moveItem(at: incoming, to: target)
                }
                return
            } catch {
                let ns = error as NSError
                if Task.isCancelled || error is CancellationError || (ns.domain == NSURLErrorDomain && ns.code == NSURLErrorCancelled) {
                    throw CancellationError()
                }
                lastError = error
                log.notice("\(entry.localPath, privacy: .public) failed from \(source.rawValue, privacy: .public)")
            }
        }
        throw lastError
    }

    /// A download with byte progress: a session of its own with a session
    /// delegate — the async `download(from:delegate:)` doesn't deliver
    /// `didWriteData` to a task delegate (review 21.10).
    private static let defaultFetch: Fetch = { url, written in
        try await DelegateDownload(written).run(url)
    }

    private final class DelegateDownload: NSObject, URLSessionDownloadDelegate, @unchecked Sendable {
        private let written: @Sendable (Int64) -> Void
        private let lock = NSLock()
        private var continuation: CheckedContinuation<(URL, URLResponse), Error>?
        private var finished: (URL, URLResponse)?
        private var task: URLSessionDownloadTask?
        /// Set by a cancel that came before a task existed to cancel.
        private var cancelled = false
        /// A long transfer the CDN cut (seen at ~2.5 MB/s on the 1.3 GB
        /// Whisper weights, 21.10) resumes from where it stopped — this
        /// many times — before the file goes to the other host.
        private static let resumes = 3

        init(_ written: @escaping @Sendable (Int64) -> Void) { self.written = written }

        func run(_ url: URL) async throws -> (URL, URLResponse) {
            let session = URLSession(configuration: .ephemeral, delegate: self, delegateQueue: nil)
            defer { session.finishTasksAndInvalidate() }
            var resumeData: Data?
            for attempt in 0...Self.resumes {
                do {
                    return try await once(session, url: url, resumeData: resumeData)
                } catch {
                    let ns = error as NSError
                    guard attempt < Self.resumes, !Task.isCancelled,
                          let data = ns.userInfo[NSURLSessionDownloadTaskResumeData] as? Data else { throw error }
                    resumeData = data
                }
            }
            throw Failure.integrity
        }

        private func once(_ session: URLSession, url: URL, resumeData: Data?) async throws -> (URL, URLResponse) {
            lock.withLock { finished = nil }
            return try await withTaskCancellationHandler {
                try await withCheckedThrowingContinuation { continuation in
                    let start: Bool = lock.withLock {
                        // A cancel that landed before this attempt had a task
                        // would otherwise start a download nothing stops.
                        guard !cancelled else { return false }
                        self.continuation = continuation
                        let task = resumeData.map { session.downloadTask(withResumeData: $0) } ?? session.downloadTask(with: url)
                        self.task = task
                        task.resume()
                        return true
                    }
                    if !start { continuation.resume(throwing: CancellationError()) }
                }
            } onCancel: {
                lock.withLock { () -> URLSessionDownloadTask? in
                    cancelled = true
                    return task
                }?.cancel()
            }
        }

        func urlSession(_ session: URLSession, downloadTask: URLSessionDownloadTask, didWriteData bytesWritten: Int64,
                        totalBytesWritten: Int64, totalBytesExpectedToWrite: Int64) {
            written(totalBytesWritten)
        }

        func urlSession(_ session: URLSession, downloadTask: URLSessionDownloadTask, didFinishDownloadingTo location: URL) {
            // The system deletes `location` when this returns: move it now.
            let kept = FileManager.default.temporaryDirectory.appendingPathComponent("daisy-model-" + UUID().uuidString)
            do {
                try FileManager.default.moveItem(at: location, to: kept)
                if let response = downloadTask.response { lock.withLock { finished = (kept, response) } }
            } catch {}
        }

        func urlSession(_ session: URLSession, task: URLSessionTask, didCompleteWithError error: Error?) {
            let (continuation, result) = lock.withLock { () -> (CheckedContinuation<(URL, URLResponse), Error>?, (URL, URLResponse)?) in
                defer { self.continuation = nil }
                return (self.continuation, finished)
            }
            if let error {
                continuation?.resume(throwing: error)
            } else if let result {
                continuation?.resume(returning: result)
            } else {
                continuation?.resume(throwing: Failure.integrity)
            }
        }
    }

    private final class ByteCounter: @unchecked Sendable {
        private let lock = NSLock()
        private var value: Int64 = 0
        func add(_ bytes: Int64) -> Int64 { lock.withLock { value += bytes; return value } }
        func peek() -> Int64 { lock.withLock { value } }
    }

    // MARK: Before a library downloads

    /// Called where a library would open its own download window: fetch
    /// the set ourselves first. Returns whether it worked; if not, the
    /// caller goes on to the library's Hugging Face download as before.
    ///
    /// Runs off the main actor (hashing a 1.3 GB file there froze the UI —
    /// review 21.10); a cancellation is passed on, not turned into the
    /// library's download; a disk without room for the set is left to the
    /// library's own space check.
    static func prefetchBeforeLibraryDownload(_ set: ModelSet, whisperRoot: URL? = nil,
                                              progress: (@Sendable (Double) -> Void)? = nil) async throws -> Bool {
        guard let directory = destination(for: set, whisperRoot: whisperRoot),
              let files = try? entries(for: set, in: catalog()) else { return false }
        let needed = files.reduce(Int64(0)) { $0 + $1.file.size }
        // The home folder: on a new Mac the cache folders don't exist yet,
        // and a missing path measures as nothing (review 21.10).
        if let free = DiskSpace.freeBytes(at: FileManager.default.homeDirectoryForCurrentUser), free < needed + needed / 5 {
            log.notice("\(set.name, privacy: .public): not enough free space to fetch it — the library's check follows")
            return false
        }
        let work = Task.detached(priority: .userInitiated) {
            try await prefetch(set, into: directory, progress: progress)
        }
        do {
            try await withTaskCancellationHandler {
                try await work.value
            } onCancel: {
                work.cancel()
            }
            return true
        } catch is CancellationError {
            throw CancellationError()
        } catch {
            log.notice("\(set.name, privacy: .public) not fetched from the mirror or pinned Hugging Face (\(error.localizedDescription, privacy: .public)) — the library's own download follows")
            return false
        }
    }
}
